"""Bake UAL2 sword clips into rig-independent per-frame targets for anim/swordplay.rs.

Frame layout (our body frame: x = the anatomical RIGHT, y = up, z = forward; UAL2 is mirrored
across X onto it, so its right hand becomes our +X sword hand). Lengths are in UAL leg lengths,
heights from the ground; rotations are world deltas from the T-pose (x, y, z, w).
  0  pelvis pos (3)      3  pelvis rot (4)    7 chest rot (4)   11 head rot (4)
 15  R upper dir (3)    18  R fore dir (3)   21 blade dir (3)  24 edge dir (3)
 27  L upper dir (3)    30  L fore dir (3)
 33  L ankle pos (3)    36  L knee pole (3)  39 L foot rot (4)
 43  R ankle pos (3)    46  R knee pole (3)  49 R foot rot (4)   = 53
The knee pole is the unit direction from the hip-ankle line out to the knee.
"""
import sys, numpy as np
sys.path.insert(0, 'combat')
from ual import Rig, qmul

FPS = 30.0
r = Rig()
M = np.array([-1.0, 1.0, 1.0])


def qinv(q):
    return q * np.array([-1, -1, -1, 1.0])


def mq(q):  # mirror a world rotation across X: (x, -y, -z, w)
    return q * np.array([1, -1, -1, 1.0])


def unit(v):
    return v / np.linalg.norm(v, axis=-1, keepdims=True)


_, T = r.sample('A_TPose', FPS)
ref = {n: T[n][1][0] for n in ('pelvis', 'spine_03', 'Head', 'foot_l', 'foot_r')}
legL = np.linalg.norm(T['calf_l'][0][0] - T['thigh_l'][0][0]) + np.linalg.norm(T['foot_l'][0][0] - T['calf_l'][0][0])
REST_PELVIS_Y = T['pelvis'][0][0][1] / legL
REST_ANKLE_Y = 0.5 * (T['foot_l'][0][0][1] + T['foot_r'][0][0][1]) / legL


def bake(clip):
    ts, P = r.sample(clip, FPS)
    pos = lambda n: P[n][0] * M / legL
    rot = lambda n: mq(qmul(P[n][1], qinv(np.broadcast_to(ref[n], P[n][1].shape))))
    dirn = lambda a, b: unit((P[b][0] - P[a][0]) * M)

    def pole(sd):
        h, k, a = P['thigh_' + sd][0], P['calf_' + sd][0], P['foot_' + sd][0]
        d = unit(a - h)
        v = k - h
        return unit((v - np.sum(v * d, -1, keepdims=True) * d) * M)
    blade = unit((P['index_01_r'][0] - P['pinky_01_r'][0]) * M)
    edge = (P['middle_01_r'][0] - P['hand_r'][0]) * M
    edge = unit(edge - np.sum(edge * blade, -1, keepdims=True) * blade)
    cols = [pos('pelvis'), rot('pelvis'), rot('spine_03'), rot('Head'),
            dirn('upperarm_r', 'lowerarm_r'), dirn('lowerarm_r', 'hand_r'), blade, edge,
            dirn('upperarm_l', 'lowerarm_l'), dirn('lowerarm_l', 'hand_l'),
            pos('foot_l'), pole('l'), rot('foot_l'),
            pos('foot_r'), pole('r'), rot('foot_r')]
    F = np.concatenate(cols, -1)
    assert F.shape[1] == 53, F.shape
    # Blade-tip speed (a 0.9 m blade) marks the strike.
    tip = P['hand_r'][0] + 0.9 * unit(P['index_01_r'][0] - P['pinky_01_r'][0])
    sp = np.r_[0, np.linalg.norm(np.diff(tip, axis=0), axis=1) * FPS]
    return F, ts[int(np.argmax(sp))]


clips = sys.argv[1].split(',')
TP, _ = bake('A_TPose')
out = ['//! Generated by the UAL2 sword bake (tools/ual_retarget/bake.py) from Quaternius\' Universal',
       '//! Animation Library 2 (CC0). Layout: see `swordplay::Frame`. Do not edit by hand.',
       '', '#![allow(clippy::excessive_precision)]', '',
       f'pub(super) const FPS: f32 = {FPS:.1f};',
       '/// The T-pose (the rig-neutral reference the clips are measured from).',
       'pub(super) const TPOSE: [f32; 53] = [' + ', '.join(f'{v:.4f}' for v in TP[0]) + '];', '']
for c in clips:
    F, hit = bake(c)
    nm = ''.join(ch if ch.isalnum() else '_' for ch in c).upper()
    out.append(f'/// `{c}`: {len(F)} frames ({len(F) / FPS:.2f} s), blade fastest at {hit:.3f} s.')
    if not c.endswith('_Rec'):
        out.append(f'pub(super) const {nm}_HIT: f32 = {hit:.4f};')
    out.append(f'pub(super) const {nm}: [[f32; 53]; {len(F)}] = [')
    for row in F:
        out.append('    [' + ', '.join(f'{v:.4f}' for v in row) + '],')
    out.append('];')
    out.append('')
open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print('legL', legL, 'restPel', REST_PELVIS_Y, 'restAnk', REST_ANKLE_Y)
